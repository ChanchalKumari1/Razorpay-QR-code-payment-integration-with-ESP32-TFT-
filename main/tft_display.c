esp_err_t tft_init(void) {
    if (panel_handle) return ESP_OK;

    if (tft_lock == NULL) {
        tft_lock = xSemaphoreCreateMutex();
    }

    ESP_LOGI(TAG, "Initialize ILI9341 TFT...");

    static bool spi_initialized = false;
    if (!spi_initialized) {
        spi_bus_config_t buscfg = {
            .mosi_io_num = TFT_PIN_MOSI,
            .miso_io_num = -1,
            .sclk_io_num = TFT_PIN_SCLK,
            .quadwp_io_num = -1,
            .quadhd_io_num = -1,
            .max_transfer_sz = 320 * 240 * 2,
        };
        ESP_ERROR_CHECK(spi_bus_initialize(SPI2_HOST, &buscfg, SPI_DMA_CH_AUTO));
        spi_initialized = true;
    }

    if (!io_handle) {
        esp_lcd_panel_io_spi_config_t io_config = {
            .cs_gpio_num = TFT_PIN_CS,
            .dc_gpio_num = TFT_PIN_DC,
            .spi_mode = 0,
            .pclk_hz = 20 * 1000 * 1000, 
            .trans_queue_depth = 10,
            .lcd_cmd_bits = 8,
            .lcd_param_bits = 8,
        };
        ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi(SPI2_HOST, &io_config, &io_handle));
    }

    if (!panel_handle) {
        esp_lcd_panel_dev_config_t panel_config = {
            .reset_gpio_num = TFT_PIN_RST,
            .rgb_ele_order = LCD_RGB_ELEMENT_ORDER_RGB,
            .bits_per_pixel = 16,
        };
        esp_err_t ret = esp_lcd_new_panel_ili9341(io_handle, &panel_config, &panel_handle);
        if (ret != ESP_OK) return ret;

        ESP_ERROR_CHECK(esp_lcd_panel_reset(panel_handle));
        ESP_ERROR_CHECK(esp_lcd_panel_init(panel_handle));
        ESP_ERROR_CHECK(esp_lcd_panel_invert_color(panel_handle, false));
        ESP_ERROR_CHECK(esp_lcd_panel_swap_xy(panel_handle, true));
        ESP_ERROR_CHECK(esp_lcd_panel_mirror(panel_handle, true, true));
        ESP_ERROR_CHECK(esp_lcd_panel_disp_on_off(panel_handle, true));
    }

    gpio_set_direction(TFT_PIN_BL, GPIO_MODE_OUTPUT);
    gpio_set_level(TFT_PIN_BL, 1);

    tft_fill_screen(COLOR_BLACK);
    return ESP_OK;
}

void tft_fill_screen(uint16_t color) {
    if (!panel_handle || !xSemaphoreTake(tft_lock, portMAX_DELAY)) return;
    
    uint16_t *line_buffer = heap_caps_malloc(TFT_WIDTH * 2, MALLOC_CAP_DMA);
    if (line_buffer) {
        for (int i = 0; i < TFT_WIDTH; i++) line_buffer[i] = color;
        for (int y = 0; y < TFT_HEIGHT; y++) {
            esp_lcd_panel_draw_bitmap(panel_handle, 0, y, TFT_WIDTH, y + 1, line_buffer);
        }
        heap_caps_free(line_buffer);
    }
    xSemaphoreGive(tft_lock);
}

void tft_draw_image(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t *data) {
    if (!panel_handle || !xSemaphoreTake(tft_lock, portMAX_DELAY)) return;
    esp_lcd_panel_draw_bitmap(panel_handle, x, y, x + w, y + h, data);
    xSemaphoreGive(tft_lock);
}

void tft_fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
    if (!panel_handle || !xSemaphoreTake(tft_lock, portMAX_DELAY)) return;
    
    uint16_t *line_buffer = heap_caps_malloc(w * 2, MALLOC_CAP_DMA);
    if (line_buffer) {
        for (int i = 0; i < w; i++) line_buffer[i] = color;
        for (int row = 0; row < h; row++) {
            esp_lcd_panel_draw_bitmap(panel_handle, x, y + row, x + w, y + row + 1, line_buffer);
        }
        heap_caps_free(line_buffer);
    }
    xSemaphoreGive(tft_lock);
}

void tft_draw_pixel(uint16_t x, uint16_t y, uint16_t color) {
    if (!panel_handle || x >= TFT_WIDTH || y >= TFT_HEIGHT) return;
    esp_lcd_panel_draw_bitmap(panel_handle, x, y, x + 1, y + 1, &color);
}

void tft_draw_text(const char* text, uint16_t x, uint16_t y, uint16_t color, uint16_t bg_color, uint8_t size) {
    if (!panel_handle || !text) return;

    if (!xSemaphoreTake(tft_lock, pdMS_TO_TICKS(1000))) {
        ESP_LOGE(TAG, "Failed to take tft_lock for text drawing");
        return;
    }
    
    uint16_t start_x = x;
    uint16_t current_x = x;
    uint16_t current_y = y;
    int char_count = 0;
    
    while(*text && *text != '\0') {
        char c = *text++;
        if(c == '\n') {
            current_y += 8 * size;
            current_x = start_x;
            continue;
        }
        if(c < 32 || c > 126) continue;
        
        const uint8_t *glyph = font_8x8[c - 32];
        for(uint8_t row = 0; row < 8; row++) {
            uint8_t byte = glyph[row];
            for(uint8_t col = 0; col < 8; col++) {
                if(byte & (0x80 >> col)) {
                    tft_fill_rect_internal(current_x + (col * size), current_y + (row * size), size, size, color);
                } else if(bg_color != color) {
                    tft_fill_rect_internal(current_x + (col * size), current_y + (row * size), size, size, bg_color);
                }
            }
        }
        current_x += 8 * size;
        char_count++;
        if (char_count % 10 == 0) {
            xSemaphoreGive(tft_lock);
            taskYIELD();
            if (!xSemaphoreTake(tft_lock, pdMS_TO_TICKS(1000))) {
                ESP_LOGE(TAG, "Failed to re-take tft_lock");
                return;
            }
        }

        if (current_x > TFT_WIDTH - (8 * size)) {
            current_x = start_x;
            current_y += 8 * size;
        }
    }
    xSemaphoreGive(tft_lock);
}

void tft_fill_rect_internal(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color) {
    if (x >= TFT_WIDTH || y >= TFT_HEIGHT) return;
    if (x + w > TFT_WIDTH) w = TFT_WIDTH - x;
    if (y + h > TFT_HEIGHT) h = TFT_HEIGHT - y;
    
    if (w == 0 || h == 0) return;
    
    uint16_t *line_buffer = NULL;
    bool use_stack = (w <= 64); 
    
    if (use_stack) {
        uint16_t stack_buffer[64];
        line_buffer = stack_buffer;
        for (int i = 0; i < w; i++) line_buffer[i] = color;
        for (int row = 0; row < h; row++) {
            if (panel_handle && x + w <= TFT_WIDTH && y + row < TFT_HEIGHT) {
                esp_err_t ret = esp_lcd_panel_draw_bitmap(panel_handle, x, y + row, x + w, y + row + 1, line_buffer);
                if (ret != ESP_OK) {
                    ESP_LOGE(TAG, "Failed to draw bitmap: %d", ret);
                    break;
                }
            }
            if (row % 20 == 0 && row > 0) {
                taskYIELD();
            }
        }
    } else {
        line_buffer = heap_caps_malloc(w * 2, MALLOC_CAP_DMA);
        if (!line_buffer) {
            ESP_LOGE(TAG, "Failed to allocate line buffer for rect");
            return;
        }
        for (int i = 0; i < w; i++) line_buffer[i] = color;
        for (int row = 0; row < h; row++) {
            if (panel_handle && x + w <= TFT_WIDTH && y + row < TFT_HEIGHT) {
                esp_err_t ret = esp_lcd_panel_draw_bitmap(panel_handle, x, y + row, x + w, y + row + 1, line_buffer);
                if (ret != ESP_OK) {
                    ESP_LOGE(TAG, "Failed to draw bitmap: %d", ret);
                    break;
                }
            }
            if (row % 20 == 0 && row > 0) {
                taskYIELD();
            }
        }
        heap_caps_free(line_buffer);
    }
}